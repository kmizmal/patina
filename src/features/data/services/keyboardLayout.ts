/**
 * Physical keyboard geometry for the keyboard heatmap.
 *
 * These are the standard ANSI key positions shared by the 60%, 75%, TKL, full
 * and laptop layouts: a key identity, its printed legend and its rectangle.
 * All values are layout units where one 1u key is `KEY_UNIT` wide, so the
 * renderer scales one constant instead of carrying pixel offsets of its own.
 */
export interface KeyboardKey {
  /** Stable identity, matching `key_name` stored by the capture layer. */
  key: string;
  /** Printed legend. Not localized copy: these are the characters on the keys. */
  label: string;
  x: number;
  y: number;
  width: number;
  height: number;
}

