const REGION_BY_KEY = new Map<string, KeyboardRegionId>();
for (const region of KEYBOARD_REGIONS) {
  for (const key of region.keys) REGION_BY_KEY.set(key, region.id);
}

/** Region of a recorded key, or `null` for keys outside the bundled layouts. */
export function keyboardRegionFor(key: string): KeyboardRegionId | null {
  return REGION_BY_KEY.get(key) ?? null;
}
